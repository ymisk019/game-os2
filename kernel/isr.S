/* Yazan OS - kernel/isr.S  (generated: 32 CPU exception stubs)
 * Each stub normalises the stack to: [error][vector], then jumps to isr_common,
 * which saves all GPRs, calls exception_handler(regs_t*), restores and iretq's.
 * Stack is 16-byte aligned at the call (verified by tools/isr_test.c). */
.intel_syntax noprefix

.macro ISR_NOERR n
.global isr\n
isr\n:
    push 0
    push \n
    jmp isr_common
.endm

.macro ISR_ERR n
.global isr\n
isr\n:
    push \n
    jmp isr_common
.endm

